SELECT
    CASE
        WHEN DATE_PART('HOUR', EVENT_TIMESTAMP) BETWEEN 6 AND 11
            THEN 'Morning'
        WHEN DATE_PART('HOUR', EVENT_TIMESTAMP) BETWEEN 16 AND 20
            THEN 'Evening'
        ELSE 'Other'
    END AS TRAFFIC_PERIOD,

    COUNT(*) AS TOTAL_PINGS,
    COUNT(DISTINCT DEVICE_ID) AS UNIQUE_DEVICES,
    COUNT_IF(LATITUDE IS NULL OR LONGITUDE IS NULL)
        AS MISSING_COORDINATES

FROM MOBILITY_GEO_DB.RAW.RAW_DEVICE_PINGS

GROUP BY TRAFFIC_PERIOD
ORDER BY
    CASE TRAFFIC_PERIOD
        WHEN 'Morning' THEN 1
        WHEN 'Evening' THEN 2
        ELSE 3
    END;